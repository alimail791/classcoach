// Day number since 1 Jan 2026 (IST date string) → which script.
export function scriptFor(date) {
  const day = Math.round((Date.parse(`${date}T00:00:00Z`) - Date.parse("2026-01-01T00:00:00Z")) / 864e5);
  const i = ((day % SCRIPTS.length) + SCRIPTS.length) % SCRIPTS.length;
  return { ...SCRIPTS[i], index: i };
}
